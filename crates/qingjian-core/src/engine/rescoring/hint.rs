//! 候选旁的模型标注: 这次重排把它抬 / 压了几名, 以及相对分打分器给出的置信度.

/// 一条候选在最近一次重排里的遭遇, 壳拿去在候选后面标 `AI 76% ↑2` 这样的字样.
///
/// 位移两种打分器都算得出 (字级模型一样在改排序), 置信度只有相对分才算得出: 字级模型的整句
/// log 概率不是概率, 硬折算成百分比只是假精度, 所以那种情况下 `confidence` 是 `None`, 壳只标 `AI`.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ModelHint {
    /// 名次变化: 被抬上来为正 (原来第 3 名, 重排后第 1 名就是 `2`), 被压下去为负.
    pub shift: i16,

    /// 相对分打分器给这条候选的置信度 (0 到 1); 字级模型这类没有概率语义的为 `None`.
    pub confidence: Option<f32>,
}

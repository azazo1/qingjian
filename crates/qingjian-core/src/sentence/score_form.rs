//! 整句重打分器给出的分是什么量纲：字级语言模型给整句 log 概率，判断类模型只给同一批之间的相对优劣。

/// 整句重打分器给出的分是什么量纲。
///
/// 两种接法的差别只在重排怎么用这个分：字级语言模型给的是「这条整句的 log 概率」，本身与路径分里的静态模型
/// 同量纲，可以直接顶掉；判断类模型（决策模型）只回答「这几条里哪条更顺」，数值本身不是概率，也就没有绝对意义，
/// 只能在同一批候选之间比，所以重排前先按批内均值居中。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum ScoreForm {
    /// 整句的 `log P(文本 | 前文)`：重排时替换路径分里静态语言模型那部分，个人 n-gram 与用户加分原样保留。
    #[default]
    Absolute,

    /// 同一批候选之间的相对优劣（越大越好，数值本身无意义）：重排时按批内均值居中后叠加。
    Relative,
}
